/** 生成 mock 行：按记账日期顺序滚出初始余额列 */
export function buildJournalRows() {
	let balance = 0
	return RAW.map((r, i) => {
		const row = {
			id: i + 1,
			date: r[0],
			op_date: r[1],
			doc_type: r[2],
			doc_no: r[3],
			voucher_no: r[4],
			subject_id: r[5],
			subject: r[6],
			summary: r[7],
			income: r[8],
			outcome: r[9],
			salesman: r[10],
			is_red: !!r[11],
		}
		balance += row.income - row.outcome
		row.balance = balance
		return row
	})
}

/** 按当前行序重算余额列（「科目余额重排」按钮用），返回新数组不改源数据 */
export function reorderBalances(rows) {
	let balance = 0
	return rows.map((row) => {
		balance += row.income - row.outcome
		return { ...row, balance }
	})
}

/** 生成凭证分录（凭证头 + 分录的只读穿透数据）：本行流水 + 对方科目对冲 */
export function buildEntries(row) {
	const counter = counterSubject(row.doc_type)
	return [
		{ summary: row.summary, subject: row.subject, debit: row.income, credit: row.outcome },
		{ summary: row.summary, subject: counter, debit: row.outcome, credit: row.income },
	]
}
