/** 生成 mock 行：按日期顺序、分科目滚动余额列；方向=本行发生方 */
export function buildSubjectRows() {
	const running = new Map() // subject_id -> 余额
	return RAW.map((r, i) => {
		const [date, doc_type, doc_no, subject_id, subject, summary, debit, credit, before_open] = r
		const bal = (running.get(subject_id) || 0) + debit - credit
		running.set(subject_id, bal)
		return {
			id: i + 1,
			date,
			doc_type,
			doc_no,
			subject_id,
			subject,
			summary,
			debit,
			credit,
			direction: debit > 0 ? '借' : '贷',
			balance: bal,
			before_open: !!before_open,
		}
	})
}
